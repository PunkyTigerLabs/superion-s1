"""Write superion-s1.marketplace.yaml: the spec for resellers (RapidAPI, AWS…).

Resellers call the API with ONE contract key shared by all their subscribers, so key management and
account endpoints must not be exposed: a subscriber could rotate or revoke the contract key, or read its usage.
Kept: POST /v1/systemone, GET /v1/models, GET /health.
"""
import copy
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
spec = yaml.safe_load((ROOT / "superion-s1.yaml").read_text())
out = copy.deepcopy(spec)
out["paths"] = {p: v for p, v in spec["paths"].items() if p in ("/v1/systemone", "/v1/models", "/health")}
out["tags"] = [t for t in spec["tags"] if t["name"] != "Account"]
out["info"]["title"] = "Superion S1 API (marketplace)"
out["info"]["description"] = spec["info"]["description"].replace(
    "**Plans.**", "Account and key-management endpoints are not available through marketplaces.\n\n    **Plans.**")
for name in ("Usage", "RotatedKey"):
    out["components"]["schemas"].pop(name)
(ROOT / "superion-s1.marketplace.yaml").write_text(
    "# GENERATED by scripts/make_marketplace_spec.py — do not edit by hand\n" + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=120))
